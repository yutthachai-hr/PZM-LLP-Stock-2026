#!/usr/bin/env node
// G25 rolling release (8 Oct 2026): the one-release TRANSITION rules, generated from the strict
// firestore.rules so the two can never drift.
//
// Production's rules (main) know no `version` on products and orders; the strict rules require
// every non-admin edit to move it by exactly 1. Either order of deploying breaks someone:
//   - strict rules first: old PWA tabs (no version) are refused on every product / order edit;
//   - the new app first: its `version` field is refused by main's closed field list.
// The transition rules accept BOTH: the field is allowed, and a non-admin edit may leave it as
// it was (an old tab) or move it by 1 (a new tab). Deploy order: transition rules → app → wait
// for old tabs to update → strict rules. docs/release/rc-readiness.md has the steps.
//
//   node scripts/rules-transition.mjs            write firestore.transition.rules
//   node scripts/rules-transition.mjs --check    exit 1 if it is out of date
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const strict = readFileSync(resolve(root, 'firestore.rules'), 'utf8').replace(/\r\n/g, '\n')
const from = `    function versionMoved() {
      return roleIsAdmin()
        || request.resource.data.get('version', 0) == resource.data.get('version', 0) + 1;
    }`
const to = `    // TRANSITION (generated by scripts/rules-transition.mjs — do not edit): an old app tab
    // leaves the version as it was; a new one moves it by 1. Both are accepted for one release.
    function versionMoved() {
      return roleIsAdmin()
        || request.resource.data.get('version', 0) == resource.data.get('version', 0) + 1
        || request.resource.data.get('version', 0) == resource.data.get('version', 0);
    }`
if (!strict.includes(from)) {
  console.error('versionMoved() in firestore.rules no longer has the expected shape — update scripts/rules-transition.mjs')
  process.exit(1)
}
const header = '// GENERATED from firestore.rules by scripts/rules-transition.mjs — the G25 one-release transition ruleset.\n// Do not edit; edit firestore.rules and regenerate.\n'
const out = header + strict.replace(from, to)
const target = resolve(root, 'firestore.transition.rules')
if (process.argv.includes('--check')) {
  let cur = ''
  try {
    cur = readFileSync(target, 'utf8').replace(/\r\n/g, '\n')
  } catch {
    // missing counts as stale
  }
  if (cur !== out) {
    console.error('firestore.transition.rules is out of date — run node scripts/rules-transition.mjs')
    process.exit(1)
  }
  console.log('transition rules fresh')
} else {
  writeFileSync(target, out)
  console.log('wrote firestore.transition.rules')
}
